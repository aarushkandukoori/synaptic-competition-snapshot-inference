'''Replicator-style synaptic-competition simulator (SYNTHETIC / MOCK data).

Reference implementation of a PROPOSAL; no experiments have been run and
nothing here is validated against real connectomic data. Model follows the
proposal: p_i(t) proportional to p_i(0) * exp(beta_i * t), with within-target
relative advantages beta_i (sum to zero), elimination below threshold theta,
and an optional segmentation-noise layer.
'''
from dataclasses import dataclass

import numpy as np

SYNTHETIC_LABEL = 'SYNTHETIC/MOCK - generated by the in-repo simulator; not real data'
PRIOR_RANGES = {'sigma_beta': (0.1, 1.5), 'theta': (0.02, 0.2), 'sigma0': (0.1, 1.0)}
PARAM_NAMES = tuple(PRIOR_RANGES)


@dataclass(frozen=True)
class NoiseConfig:
    '''Synthetic segmentation noise: size jitter, missed and merged inputs.'''
    size_sigma: float = 0.0
    p_missed: float = 0.0
    p_merge: float = 0.0


def sample_prior(rng):
    '''Draw phi = (sigma_beta, theta, sigma0) from a uniform toy prior.'''
    return np.array([rng.uniform(*PRIOR_RANGES[k]) for k in PARAM_NAMES])


def shares_at(p0, beta, t):
    '''Closed-form shares: softmax(log p0 + beta * t).'''
    z = np.log(np.asarray(p0)) + np.asarray(beta) * t
    z = z - z.max()
    e = np.exp(z)
    return e / e.sum()


def euler_shares(p0, eta, a, t, dt=1e-3):
    '''Forward-Euler integration of dw_i/dt = eta w_i (a_i - abar), for checks.'''
    w = np.array(p0, dtype=float)
    a = np.asarray(a, dtype=float)
    for _ in range(int(round(t / dt))):
        p = w / w.sum()
        w = w + dt * eta * w * (a - (p * a).sum())
    return w / w.sum()


def elimination_time_two(x0, theta, rate_diff):
    '''t* = (log((1-theta)/theta) - x0) / (eta * Delta) for two inputs.'''
    return (np.log((1 - theta) / theta) - x0) / rate_diff


def apply_noise(rng, sizes, noise):
    '''Apply synthetic segmentation noise; always keeps at least one input.'''
    sizes = np.asarray(sizes, dtype=float)
    if noise.size_sigma > 0:
        sizes = sizes * np.exp(rng.normal(0.0, noise.size_sigma, sizes.size))
    if noise.p_missed > 0 and sizes.size > 1:
        kept = rng.random(sizes.size) >= noise.p_missed
        if not kept.any():
            kept[np.argmax(sizes)] = True
        sizes = sizes[kept]
    if noise.p_merge > 0 and sizes.size > 1 and rng.random() < noise.p_merge:
        i, j = rng.choice(sizes.size, size=2, replace=False)
        merged = sizes[i] + sizes[j]
        sizes = np.append(np.delete(sizes, [i, j]), merged)
    return np.sort(sizes)[::-1]


def simulate_target(rng, age, phi, noise):
    '''One synthetic target: surviving input sizes (descending) at `age`.'''
    sigma_beta, theta, sigma0 = phi
    n = int(rng.integers(2, 7))
    p0 = np.exp(rng.normal(0.0, sigma0, n))
    p0 = p0 / p0.sum()
    b = rng.normal(0.0, sigma_beta, n)
    beta = b - b.mean()
    p = shares_at(p0, beta, age)
    keep = p >= theta
    keep[np.argmax(p)] = True
    return apply_noise(rng, p[keep], noise)


def simulate_snapshot(rng, ages, n_targets, phi, noise=NoiseConfig()):
    '''List (one entry per age) of lists of per-target size arrays.

    Targets are independent draws per age (cross-sectional design).
    '''
    return [[simulate_target(rng, t, phi, noise) for _ in range(n_targets)]
            for t in ages]
